#!/usr/bin/env python3
"""Download the exact Commons files used by the chapters and retain attribution.

Only files with an explicit free license or public domain mark are accepted.
Existing downloads are kept; failed images are reported and left out of manifest.
"""
import hashlib
import html
import json
import pathlib
import re
import ssl
import sys
import time
import urllib.parse
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
HEADERS = {"User-Agent": "TyumenJourney/1.0 (educational historical atlas; Commons attribution retained)"}
SYSTEM_CA = pathlib.Path('/etc/ssl/cert.pem')
TLS = ssl.create_default_context(cafile=str(SYSTEM_CA) if sys.platform == 'darwin' and SYSTEM_CA.exists() else None)


def get(url):
    for attempt in range(3):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=HEADERS), timeout=40, context=TLS) as response:
                return response.read()
        except Exception:
            if attempt == 2:
                raise
            time.sleep(2 ** (attempt + 1))


def plain(value):
    return html.unescape(re.sub(r"<[^>]*>", "", value or "")).strip()


def main():
    raw = (ROOT / "content/chapters.js").read_text()
    content = json.loads(raw.split("window.JOURNEY_CONTENT = ", 1)[1].strip().rstrip(";"))
    photos = {}
    for chapter in content["chapters"]:
        items = [chapter["photo"]] + chapter.get("gallery", [])
        if chapter.get("thenNow"):
            items += [chapter["thenNow"][key] for key in ("then", "now")]
        for photo in items:
            photos[photo["file"]] = photo
    destination = ROOT / "assets/photos"
    destination.mkdir(parents=True, exist_ok=True)
    previous = json.loads((destination / 'attribution.json').read_text()) if (destination / 'attribution.json').exists() else {}
    manifest, attribution, failures = {}, {}, {}
    for filename, photo in photos.items():
        try:
            query = urllib.parse.urlencode({"action": "query", "format": "json", "prop": "imageinfo",
                "iiprop": "url|extmetadata", "iiurlwidth": 1600, "titles": "File:" + filename})
            data = json.loads(get("https://commons.wikimedia.org/w/api.php?" + query))
            page = next(iter(data["query"]["pages"].values()))
            info = page["imageinfo"][0]
            metadata = info.get("extmetadata", {})
            value = lambda key: plain(metadata.get(key, {}).get("value", ""))
            license_name = value("LicenseShortName")
            if not re.fullmatch(r"CC ?(?:BY(?:-SA)?|0)(?: [\d.]+)?|Public domain|GFDL(?: [\d.]+)?", license_name, re.I):
                raise ValueError("License requires review: " + license_name)
            url = info.get("thumburl") or info["url"]
            extension = pathlib.PurePosixPath(urllib.parse.urlsplit(url).path).suffix.lower()
            if extension not in (".jpg", ".jpeg", ".png", ".webp"):
                raise ValueError("Unsupported image format: " + extension)
            local_name = hashlib.sha256(filename.encode()).hexdigest()[:16] + extension
            target = destination / local_name
            if not target.exists():
                image = get(url)
                if not (image.startswith(b"\xff\xd8") or image.startswith(b"\x89PNG") or image.startswith(b"RIFF")):
                    raise ValueError("Response is not a raster image")
                target.write_bytes(image)
            manifest[filename] = "assets/photos/" + local_name
            attribution[filename] = {"page": info["descriptionurl"], "download": url,
                "artist": value("Artist"), "credit": value("Credit"), "license": license_name,
                "licenseUrl": value("LicenseUrl"), "attributionRequired": value("AttributionRequired"),
                "local": manifest[filename]}
            print("OK", filename, flush=True)
        except Exception as error:
            failures[filename] = str(error)
            retained = previous.get(filename)
            if retained and (ROOT / retained['local']).is_file():
                manifest[filename] = retained['local']
                attribution[filename] = retained
            print("MISSING", filename, str(error), flush=True)
        time.sleep(1)
    (destination / "manifest.js").write_text("// Generated by tools/download_photos.py\nwindow.JOURNEY_LOCAL_PHOTOS = " + json.dumps(manifest, ensure_ascii=False, indent=2) + ";\n")
    (destination / "attribution.json").write_text(json.dumps(attribution, ensure_ascii=False, indent=2) + "\n")
    (destination / "missing.json").write_text(json.dumps(failures, ensure_ascii=False, indent=2) + "\n")
    print(f"Saved {len(manifest)}/{len(photos)} photos. Missing: {len(failures)}.")
    return int(bool(failures))


if __name__ == "__main__":
    raise SystemExit(main())
